/** Decorative: always sits beside the visible tool name, so it is hidden from assistive tech. */
export function ToolMark({
  tool,
  size = "md",
}: {
  tool: AiToolId;
  size?: "sm" | "md";
}) {
  const { name, mark } = aiTools[tool];
  return (
    <span
      className="tool-mark"
      data-size={size}
      data-mark={mark ?? "monogram"}
      aria-hidden="true"
    >
      {mark ? (
        <svg
          viewBox={marks[mark].viewBox}
          fill="currentColor"
          focusable="false"
        >
          {marks[mark].body}
        </svg>
      ) : (
        <span className="tool-mark-monogram">{name.charAt(0)}</span>
      )}
    </span>
  );
}
